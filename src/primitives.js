export const primitiveNames = Object.freeze(Object.keys(loaders));
export async function loadPrimitives(names) {
  if (!Array.isArray(names)) throw new TypeError('Primitive names must be an array');
  for (const name of names) if (!Object.hasOwn(loaders,name)) throw new RangeError(`Unknown free primitive: ${name}`);
  await Promise.all([...new Set(names)].map(name=>loaders[name]()));
}
